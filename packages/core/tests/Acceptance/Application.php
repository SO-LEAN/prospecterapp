    /**
     * The command that a handler carries out, found the way the API's command bus finds it: the type of
     * __invoke()'s argument.
     *
     * @return class-string
     */
    private function commandOf(CommandHandler $handler): string
    {
        $type = new \ReflectionMethod($handler, '__invoke')->getParameters()[0]->getType();

        return $type instanceof \ReflectionNamedType && (class_exists($type->getName()) || interface_exists($type->getName())) ? $type->getName() : throw new \LogicException(sprintf('%s::__invoke() must take one command', $handler::class));
    }

    /**
     * Asks a query and presents its answer to the given output port. Returns false when the query was refused.
     */
    private function ask(QueryHandler $handler, object $query, object $output): bool
    {
        return null !== $this->attempt(static function () use ($handler, $query, $output): bool {
            new RefusalTranslatingQueryHandler($handler)($query, $output);

            return true;
        });
    }

    /**
     * @template T
     *
     * @param \Closure(): T $call
     *
     * @return T|null
     */
    private function attempt(\Closure $call): mixed
    {
        $this->refusal = null;

        try {
            return $call();
        } catch (UseCaseRefused $refusal) {
            $this->refusal = $refusal;

            return null;
        }
    }
